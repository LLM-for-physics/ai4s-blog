import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// The checked-in notebook is the source of truth. This converter never executes it.
export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const assetDirectory = 'docs/public/classroom/2026-fall/notebook'
export const notebookFile = assetDirectory + '/课堂展示-new.ipynb'
export const pageFile = 'docs/course/neural-network-practice.md'
const publicPath = '/classroom/2026-fall/notebook'
const generatedImagePattern = /^cell-\d+-output-\d+\.png$/
function fail(context, message) { throw new Error(context + ': ' + message) }

export function multiline(value, context) {
  if (typeof value === 'string') return value
  if (Array.isArray(value) && value.every(part => typeof part === 'string')) return value.join('')
  fail(context, 'expected a string or an array of strings')
}

// A longer fence cannot be closed by backticks inside code or output.
// VitePress renders code fences with v-pre, keeping {{ }} and HTML literal.
export function codeFence(text, language = 'text') {
  const backtick = String.fromCharCode(96)
  const longest = Math.max(0, ...Array.from(text.matchAll(new RegExp(backtick + '+', 'g')), match => match[0].length))
  const fence = backtick.repeat(Math.max(3, longest + 1))
  return fence + language + '\n' + text + (text.endsWith('\n') ? '' : '\n') + fence
}

function executionLabel(value, context) {
  if (value === null) return ' '
  if (Number.isInteger(value) && value >= 0) return String(value)
  fail(context, 'execution_count must be an integer or null')
}

function renderTextOutput(text) {
  const content = codeFence(text)
  const lines = text.replace(/\r?\n$/, '').split(/\r?\n/).length
  if (lines <= 40) return content
  return '<details class="notebook-long-output">\n<summary>展开完整输出（' + lines + ' 行）</summary>\n\n' + content + '\n\n</details>'
}

function imageDescription(source, cellNumber) {
  if (source.includes('plt.plot(loss_list)')) return '训练损失随训练轮数变化的曲线（对数纵轴）'
  if (source.includes("label='NN'")) return '神经网络拟合结果与目标函数的对比'
  if (source.includes('np.abs((V_real-V_model)/V_real)')) return '神经网络预测相对于目标函数的相对误差'
  return 'Notebook 第 ' + cellNumber + ' 个单元的图像输出'
}

function decodePng(value, context) {
  const base64 = multiline(value, context).replace(/\s/g, '')
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(base64)) fail(context, 'invalid PNG base64 data')
  const data = Buffer.from(base64, 'base64')
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])
  if (data.length < 24 || !data.subarray(0, 8).equals(signature)) fail(context, 'invalid PNG signature')
  return data
}

function promotePageHeading(source) {
  let fence = null
  return source.split('\n').map(line => {
    const match = line.match(/^\s{0,3}([`~]{3,})(.*)$/)
    if (match && /^(\x60+|~+)$/.test(match[1])) {
      if (!fence) fence = match[1]
      else if (match[1][0] === fence[0] && match[1].length >= fence.length && !match[2].trim()) fence = null
      return line
    }
    return fence ? line : line.replace(/^# /, '## ')
  }).join('\n')
}


export function renderNotebook(notebook) {
  if (notebook.nbformat !== 4 || !Array.isArray(notebook.cells)) fail('notebook', 'only nbformat 4 notebooks with a cells array are supported')
  const images = []
  const sections = [
    '<!-- Generated by scripts/render-classroom-notebook.mjs. Edit the source .ipynb, then regenerate. -->',
    '# 神经网络实践',
    '这里按 Notebook 中的顺序展示说明、代码和已经保存的运行结果。页面可以直接阅读；需要自己运行时，可以下载原文件。',
    '<a href="' + publicPath + '/课堂展示-new.ipynb" download="课堂展示-new.ipynb">下载原始 Notebook（.ipynb）</a>',
  ]
  const stats = { markdownCells: 0, codeCells: 0, skippedEmptyCells: 0, outputs: 0, images: 0 }
  notebook.cells.forEach((cell, cellIndex) => {
    const cellNumber = cellIndex + 1
    const context = 'cell ' + cellNumber
    if (!cell || !['markdown', 'code'].includes(cell.cell_type)) fail(context, 'unsupported cell type ' + JSON.stringify(cell?.cell_type))
    const source = multiline(cell.source, context + ' source')
    if (cell.cell_type === 'markdown') {
      if (cell.attachments && Object.keys(cell.attachments).length) fail(context, 'markdown attachments are not supported')
      stats.markdownCells++
      // Keep a single page H1 without rewriting prose or lower-level headings.
      sections.push('<!-- notebook-cell: ' + cellNumber + ' -->\n\n' + promotePageHeading(source))
      return
    }
    if (!Array.isArray(cell.outputs)) fail(context, 'code cell outputs must be an array')
    const inputCount = executionLabel(cell.execution_count, context)
    if (!source.trim() && cell.outputs.length === 0) {
      stats.skippedEmptyCells++
      return
    }
    stats.codeCells++
    const parts = [
      '<!-- notebook-cell: ' + cellNumber + ' -->',
      '<section class="notebook-cell" aria-label="代码单元 ' + cellNumber + '">',
      '<div class="notebook-cell-label">In [' + inputCount + ']</div>',
      codeFence(source, 'python'),
    ]
    cell.outputs.forEach((output, outputIndex) => {
      const outputContext = context + ', output ' + (outputIndex + 1)
      stats.outputs++
      if (!output || !['stream', 'display_data', 'execute_result'].includes(output.output_type)) fail(outputContext, 'unsupported output type ' + JSON.stringify(output?.output_type))
      let label = '输出'
      if (output.output_type === 'stream') {
        if (!['stdout', 'stderr'].includes(output.name)) fail(outputContext, 'unsupported stream ' + JSON.stringify(output.name))
        if (output.name === 'stderr') label = '标准错误输出'
        parts.push('<div class="notebook-cell-label">' + label + '</div>', renderTextOutput(multiline(output.text, outputContext)))
        return
      }
      if (output.output_type === 'execute_result') label = 'Out [' + executionLabel(output.execution_count, outputContext) + ']'
      if (!output.data || typeof output.data !== 'object' || Array.isArray(output.data)) fail(outputContext, 'missing MIME data')
      const mimeTypes = Object.keys(output.data)
      const unknown = mimeTypes.filter(type => !['text/plain', 'image/png'].includes(type))
      if (unknown.length) fail(outputContext, 'unsupported MIME type(s): ' + unknown.join(', '))
      if (!mimeTypes.length) fail(outputContext, 'empty MIME data')
      parts.push('<div class="notebook-cell-label">' + label + '</div>')
      // MIME entries are alternative representations: prefer PNG, otherwise text.
      if ('image/png' in output.data) {
        const filename = 'cell-' + String(cellNumber).padStart(3, '0') + '-output-' + String(outputIndex + 1).padStart(2, '0') + '.png'
        images.push({ filename, data: decodePng(output.data['image/png'], outputContext) })
        parts.push('![' + imageDescription(source, cellNumber) + '](' + publicPath + '/' + filename + ')')
        stats.images++
      } else {
        parts.push(renderTextOutput(multiline(output.data['text/plain'], outputContext)))
      }
    })
    parts.push('</section>')
    sections.push(parts.join('\n\n'))
  })
  sections.push([
    '<style scoped>',
    '.notebook-cell { min-width: 0; margin: 1.8rem 0; }',
    '.notebook-cell-label { margin: 0.6rem 0 0.3rem; color: var(--vp-c-text-2); font-family: var(--vp-font-family-mono); font-size: 0.85rem; }',
    ".notebook-cell :deep(div[class*='language-']) { margin-top: 0.4rem; margin-bottom: 0.9rem; }",
    '.notebook-long-output { min-width: 0; margin: 0.5rem 0 1rem; padding: 0.8rem 1rem; border: 1px solid var(--vp-c-divider); border-radius: 8px; }',
    '.notebook-long-output summary { cursor: pointer; color: var(--vp-c-text-2); }',
    '</style>',
  ].join('\n'))
  return { markdown: sections.join('\n\n') + '\n', images, stats }
}

async function writeIfChanged(filename, content) {
  const expected = Buffer.isBuffer(content) ? content : Buffer.from(content)
  try {
    if ((await readFile(filename)).equals(expected)) return
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  await mkdir(path.dirname(filename), { recursive: true })
  await writeFile(filename, expected)
}

export async function renderClassroomNotebook(root = repoRoot, { check = false } = {}) {
  const notebook = JSON.parse(await readFile(path.join(root, notebookFile), 'utf8'))
  const rendered = renderNotebook(notebook)
  const files = [
    [path.join(root, pageFile), Buffer.from(rendered.markdown)],
    ...rendered.images.map(image => [path.join(root, assetDirectory, image.filename), image.data]),
  ]
  const imageNames = new Set(rendered.images.map(image => image.filename))
  const directory = path.join(root, assetDirectory)
  const stale = (await readdir(directory)).filter(name => generatedImagePattern.test(name) && !imageNames.has(name))
  if (check) {
    for (const [filename, expected] of files) {
      let actual
      try { actual = await readFile(filename) } catch (error) {
        if (error.code === 'ENOENT') fail(filename, 'generated file is missing; run node scripts/render-classroom-notebook.mjs')
        throw error
      }
      if (!actual.equals(expected)) fail(filename, 'generated content is stale; run node scripts/render-classroom-notebook.mjs')
    }
    if (stale.length) fail(directory, 'stale generated images: ' + stale.join(', '))
  } else {
    for (const [filename, expected] of files) await writeIfChanged(filename, expected)
    // Only remove filenames owned by this converter, never other course assets.
    for (const filename of stale) await unlink(path.join(directory, filename))
  }
  return rendered.stats
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  if (args.some(arg => arg !== '--check')) {
    console.error('Usage: node scripts/render-classroom-notebook.mjs [--check]')
    process.exitCode = 1
  } else {
    try {
      const stats = await renderClassroomNotebook(repoRoot, { check: args.includes('--check') })
      console.log('Notebook ' + (args.includes('--check') ? 'verified' : 'rendered') + ': ' + stats.markdownCells + ' Markdown cells, ' + stats.codeCells + ' code cells, ' + stats.outputs + ' saved outputs, ' + stats.images + ' PNGs; ' + stats.skippedEmptyCells + ' empty cells omitted. No code was executed.')
    } catch (error) {
      console.error(error.message)
      process.exitCode = 1
    }
  }
}
